/// Model representing individual conversation messages.
///
/// Encapsulates message roles, text content, multi-modal file attachments,
/// token metrics, and real-time streaming states.
library;

import 'attachment_item.dart';

/// Represents a single prompt or AI response in a chat session.
class ChatMessage {
  /// The unique identifier of the message.
  final String id;

  /// The parent conversation identifier to which this message belongs.
  final String? conversationId;

  /// The role of the author, typically `'user'`, `'assistant'`, or `'system'`.
  final String role;

  /// The markdown text content of the message.
  String content;

  /// The creation timestamp of the message.
  final DateTime createdAt;

  /// The number of tokens consumed by this message, if calculated.
  final int? tokenCount;

  /// The list of multi-modal files, documents, or photos attached to this turn.
  final List<AttachmentItem> attachments;

  /// Whether the message is currently receiving token chunks via SSE streaming.
  bool isStreaming;

  /// Whether an error occurred during message generation or transmission.
  bool isError;

  /// Creates a new [ChatMessage] instance.
  ChatMessage({
    required this.id,
    this.conversationId,
    required this.role,
    required this.content,
    required this.createdAt,
    this.tokenCount,
    this.attachments = const [],
    this.isStreaming = false,
    this.isError = false,
  });

  /// Whether this message was authored by the user.
  bool get isUser => role == 'user';

  /// Whether this message was generated by the AI assistant.
  bool get isAssistant => role == 'assistant';

  /// Deserializes a [ChatMessage] from a JSON map.
  factory ChatMessage.fromJson(Map<String, dynamic> json) {
    var rawAttachments = json['attachments'];
    List<AttachmentItem> atts = [];
    if (rawAttachments is List) {
      atts = rawAttachments
          .map((a) => AttachmentItem.fromJson(a as Map<String, dynamic>))
          .toList();
    }

    DateTime created;
    try {
      created = json['createdAt'] != null
          ? DateTime.parse(json['createdAt'].toString())
          : DateTime.now();
    } catch (_) {
      created = DateTime.now();
    }

    return ChatMessage(
      id: json['id']?.toString() ?? '',
      conversationId: json['conversationId']?.toString(),
      role: json['role']?.toString() ?? 'assistant',
      content: json['content']?.toString() ?? '',
      createdAt: created,
      tokenCount: (json['tokenCount'] as num?)?.toInt(),
      attachments: atts,
    );
  }

  /// Serializes the message to a JSON map for persistence or network transmission.
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'conversationId': conversationId,
      'role': role,
      'content': content,
      'createdAt': createdAt.toIso8601String(),
      'tokenCount': tokenCount,
      'attachments': attachments.map((a) => a.toJson()).toList(),
    };
  }
}
